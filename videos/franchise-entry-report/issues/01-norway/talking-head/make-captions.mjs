// Builds norway-take/compositions/captions.html from whisper.json: word-timed caption groups, written as real HTML
// so every group is editable in Studio. Re-run after correcting a word: node make-captions.mjs
import fs from 'node:fs';

const OFFSET = 5.6;            // the footage was trimmed to start 5.6 s into the original
// pauses cut out, in film seconds before any cut: after "teaching Norway" (draft 2), before "Link in the comments" (draft 3)
const CUTS = [[55.9333, 56.6333], [79.1, 80.0]];
const END = 84.2333;           // the film's length after the cuts and the trimmed ending
const MAX = 4;                 // words per group (conversational)
const KEY = /^(kfc|norway|norway's|fly|chicken|11|19|2027|popeyes|wingstop|nobody|nobody\.|first|second|£21|volume|serious|free|master|franchise|friday|wrw|hospitality)$/i;

// original seconds -> film seconds: drop the trimmed head, close the cut
const film = t => {
  t -= OFFSET;
  let out = t;
  for (const [a, b] of CUTS) { if (t >= b) out -= b - a; else if (t > a) out -= t - a; }
  return out;
};
const words = JSON.parse(fs.readFileSync(new URL('./whisper.json', import.meta.url))).words
  .map(w => ({ text: w.word.trim(), s: +film(w.start).toFixed(2), e: +Math.min(film(w.end), END - 0.05).toFixed(2) }))
  .filter(w => w.text && w.e > 0);

// group: break at a sentence end, a comma after two words, a pause of 150 ms or more, or MAX words
const groups = [];
let cur = [];
words.forEach((w, i) => {
  cur.push(w);
  const next = words[i + 1];
  const end = /[.?!]$/.test(w.text) || (/,$/.test(w.text) && cur.length >= 2) || !next || next.s - w.e >= 0.15 || cur.length >= MAX;
  if (end) { groups.push(cur); cur = []; }
});

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const clean = s => s.replace(/[,]$/, '');
let html = '', data = [];
groups.forEach((g, gi) => {
  const prev = groups[gi - 1], next = groups[gi + 1];
  const open = Math.max(prev ? prev._close : 0.1, g[0].s - 0.12);
  const close = Math.min(next ? next[0].s - 0.12 : END, g[g.length - 1].e + 0.35);
  g._close = Math.max(close, g[g.length - 1].e + 0.05);
  const id = `cg${gi}`;
  const chars = g.map(w => w.text).join(' ').length;
  const size = Math.round(Math.max(54, Math.min(76, 1500 / Math.max(chars, 1))));
  html += `    <div id="${id}" class="clip cap" data-start="${open.toFixed(2)}" data-duration="${(g._close - open).toFixed(2)}"><div id="${id}-in" class="cap-in" style="font-size: ${size}px">`;
  html += g.map((w, wi) => `<span id="${id}w${wi}" class="w${KEY.test(clean(w.text).replace(/[.?!]$/, '')) ? ' k' : ''}"><i></i><b>${esc(clean(w.text))}</b></span>`).join(' ');
  html += `</div></div>\n`;
  data.push([id, +open.toFixed(2), +g._close.toFixed(2), g.map(w => [w.s, w.e])]);
});

const out = `<template>
  <style>
    @font-face { font-family: "Archivo"; font-weight: 500; src: url("assets/fonts/archivo-latin-500-normal.woff2"); }
    #root { position: absolute; inset: 0; }
    /* captions sit low in the 168-1330 px safe band, over the jacket, clear of the face */
    .cap { position: absolute; left: 0; right: 0; top: 1150px; overflow: visible; }
    .cap-in { padding: 0 90px; text-align: center; font-family: "Archivo"; font-weight: 500; line-height: 1.18; color: #f3f2f2; overflow: visible; }
    .w { position: relative; display: inline-block; padding: 0 0.1em; }
    .w b { position: relative; font-weight: 500; opacity: 0.42; text-shadow: 0 2px 3px rgba(32, 30, 29, 0.55), 0 8px 26px rgba(32, 30, 29, 0.5); }
    .w i { position: absolute; left: -0.02em; right: -0.02em; top: 0.12em; bottom: 0.06em; background: #ec3013; transform: scaleX(0); transform-origin: 0% 50%; }
    .w.k b { text-shadow: none; }
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
${html}  </div>
  <script>
    // generated by make-captions.mjs from whisper.json; times are film seconds
    const spring = (z, w) => { const wd = w * Math.sqrt(1 - z * z), dur = 6 / (z * w); return { dur, ease: (p) => { const t = p * dur; return 1 - Math.exp(-z * w * t) * (Math.cos(wd * t) + ((z * w) / wd) * Math.sin(wd * t)); } }; };
    const rise = spring(0.78, 20), mark = spring(0.62, 22);
    const G = ${JSON.stringify(data)};
    const tl = gsap.timeline({ paused: true });
    for (const [id, open, close, ws] of G) {
      tl.fromTo("#" + id + "-in", { y: 26, opacity: 0 }, { y: 0, opacity: 1, duration: Math.min(0.26, (close - open) / 3), ease: "power3.out" }, open);
      ws.forEach(([s, e], i) => {
        const w = "#" + id + "w" + i;
        // each word lights as it is spoken; key words get the red marker, which stays for the group
        tl.fromTo(w + " b", { opacity: 0.42 }, { opacity: 1, duration: 0.08, ease: "none" }, s);
        tl.fromTo(w, { scale: 1, y: 0 }, { scale: 1.07, y: -4, duration: 0.1, ease: "power2.out" }, s);
        tl.to(w, { scale: 1, y: 0, duration: Math.min(rise.dur, Math.max(0.08, close - 0.16 - (s + 0.1))), ease: rise.ease }, s + 0.1);
        if (document.querySelector(w).classList.contains("k")) tl.fromTo(w + " i", { scaleX: 0 }, { scaleX: 1, duration: mark.dur, ease: mark.ease }, s);
      });
      tl.to("#" + id + "-in", { opacity: 0, y: -14, duration: 0.14, ease: "power2.in" }, close - 0.14);
    }
    window.__timelines["captions"] = tl;
  </script>
</template>
`;
fs.writeFileSync(new URL('./norway-take/compositions/captions.html', import.meta.url), out);
console.log(groups.length, 'groups,', words.length, 'words');
