"""Build Episode 02 from the voiceover: scene lengths, word cues in every scene, index.html, captions, effects.
Re-run after any change to the voice (.vo/words-new.json). Scenes read cues with w("word") from injected WORDS."""
import json, re

WORDS = json.load(open(".vo/words-new.json"))
SCENES = [("cold", "s1", 1.0), ("law", "s2", 1.6), ("count", "s3", 1.8), ("walkaway", "s4", 2.0),
          ("fix", "s5", 2.2), ("question", "s6", 2.4)]   # (host, line, hold after the last word)
OFF, END_CARD = 0.3, 3.0
MUSIC = "assets/music-bed.mp3"

slot, start, t = {}, {}, 0.0
for host, sid, tail in SCENES:
    slot[host] = round(OFF + WORDS[sid]["duration"] + tail + 0.049, 1)
    start[host] = round(t, 2); t += slot[host]
start["endcard"] = round(t, 2); TOTAL = round(t + END_CARD, 2)

def cue(sid, word, n=1):
    c = 0
    for x in WORDS[sid]["words"]:
        if re.sub(r"[^a-z0-9'-]", "", x["text"].lower()).startswith(word):
            c += 1
            if c == n: return x["start"]
    raise KeyError(word)

# inject word cues and slot lengths into each scene
for host, sid, _ in SCENES:
    p = f"compositions/{host}.html"; s = open(p, encoding="utf-8").read()
    arr = json.dumps([[x["text"], x["start"]] for x in WORDS[sid]["words"]])
    s = re.sub(r"const WORDS = (/\*WORDS\*/)?\[.*?\];", "const WORDS = /*WORDS*/" + arr.replace("\\", "\\\\") + ";", s, count=1, flags=re.S)
    s = re.sub(r"tl\.set\(\{\}, \{\}, (/\*SLOT\*/)?[\d.]+\);", f"tl.set({{}}, {{}}, /*SLOT*/{slot[host]});", s, count=1)
    open(p, "w", encoding="utf-8").write(s)

vo_abs = {sid: round(start[host] + OFF, 2) for host, sid, _ in SCENES}
# effects land one frame after their picture (peak 0.073 s into each file)
sfx = [
    ("sfx-tick-1", start["count"] + OFF + cue("s3", "six") + 0.05, "assets/sfx-tick.mp3", 0.366, 1.5),
    ("sfx-thud", start["walkaway"] + OFF + cue("s4", "give") + 0.05, "assets/sfx-thud.mp3", 2.116, 0.25),
    ("sfx-tick-2", start["walkaway"] + OFF + cue("s4", "five") + 0.05, "assets/sfx-tick.mp3", 0.366, 1.5),
    ("sfx-tick-3", start["fix"] + OFF + cue("s5", "four") + 0.05, "assets/sfx-tick.mp3", 0.366, 1.5),
]

hosts = "\n".join(
    f'      <div id="{h}" data-composition-id="{h}" data-composition-src="compositions/{h}.html"\n'
    f'        data-start="{start[h]}" data-duration="{slot[h] if h != "endcard" else END_CARD}" data-track-index="1" data-track-kind="graphics"\n'
    f'        data-width="1080" data-height="1350"></div>' for h in [x[0] for x in SCENES] + ["endcard"])
vo = "\n".join(f'      <audio id="vo-{sid}" class="clip" src="assets/vo/{sid}.wav" data-start="{vo_abs[sid]}" data-duration="{WORDS[sid]["duration"]}" data-track-index="3" data-volume="1.1"></audio>'
               for _, sid, _ in SCENES)
fx = "\n".join(f'      <audio id="{i}" class="clip" src="{src}" data-start="{round(t0 - 0.073 + 0.033 - 0.05 + 0.05, 2)}" data-duration="{d}" data-track-index="5" data-volume="{v}"></audio>'
               for i, t0, src, d, v in sfx)
index = f"""<!doctype html>
<html lang="en-GB">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1350" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      /* The Operator's Ledger: tokens from ../DESIGN.md. Generated by .vo/build.py; edit there. */
      :root {{ --bone: #f3f2f2; --ink: #201e1d; --red: #ec3013; --deep-red: #b6240e; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1080px; height: 1350px; overflow: hidden; background: var(--bone); }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{TOTAL}" data-width="1080" data-height="1350">
      <!-- scenes -->
{hosts}

      <!-- captions: one host for every group -->
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html"
        data-start="0" data-duration="{start['endcard']}" data-track-index="2" data-track-kind="captions"
        data-width="1080" data-height="1350" style="z-index: 10"></div>

      <!-- voiceover: Wesley's cloned voice (VoiceStudio profile ca7acc09, VoxCPM2), de-plosived -->
{vo}

      <!-- music bed: ACE-Step 1.5 local, the series prompt -->
      <audio id="music" class="clip" src="{MUSIC}" data-start="0" data-duration="{TOTAL}" data-track-index="4"
        data-volume="0.17" data-fade-in="1.0" data-fade-out="2.5"></audio>

      <!-- effects: each lands one frame after its picture -->
{fx}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
open("index.html", "w", encoding="utf-8").write(index)

# captions: same builder as Episode 01, with this episode's offsets; "P and L" is shown as P&L
c = open(".vo/captions.py", encoding="utf-8").read()
c = re.sub(r"OFFSETS = \{[^}]*\}", "OFFSETS = " + json.dumps(vo_abs), c)
c = c.replace('data = json.load(open(".vo/words.json"))', 'data = json.load(open(".vo/words-new.json"))')
c = re.sub(r"tl\.set\(\{\{\}\}, \{\{\}\}, [\d.]+\);", f"tl.set({{{{}}}}, {{{{}}}}, {start['endcard']});", c)
if "P and L" not in c:
    c = c.replace('text=" ".join(x["text"] for x in cur)', 'text=" ".join(x["text"] for x in cur).replace("P and L", "P&L")')
open(".vo/captions.py", "w", encoding="utf-8").write(c)

print("slots", slot); print("starts", start, "total", TOTAL)
print("sfx", [(i, round(t0, 2)) for i, t0, *_ in sfx])
